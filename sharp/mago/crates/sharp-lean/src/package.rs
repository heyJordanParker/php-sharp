/// The folder in the `.sharp` folder that holds the Lake package of the project's laws.
pub const PACKAGE_FOLDER: &str = ".lean";

/// How every generated module starts: it imports the runtime library.
const HEADER: &str = "-- Generated by mago compile. Do not edit.\nimport Sharp.Lean.Law\nimport Sharp.Lean.String\nimport Sharp.Lean.Interface\n";

/// What every generated module sets after its imports: a translated `match` ends in an arm for every value its arms
/// leave, and Lean may see that they leave none.
const OPTIONS: &str = "set_option match.ignoreUnusedAlts true\n";

/// Every declaration of every translation, indexed by its Lean name.
pub(crate) struct Program<'program> {
    translations: &'program [Translation],
    declarations: HashMap<&'program str, (usize, &'program Declaration)>,
    /// The declarations in a cycle of uses that Lean cannot see end: a recursion that does not get smaller, of methods,
    /// or of types.
    recursive: HashMap<&'program str, Unmodeled>,
    /// The methods in a cycle of calls that each pass a smaller value, which Lean sees end by their measure.
    terminating: HashSet<&'program str>,
}

/// Why a declaration cannot be written to Lean.
#[derive(Default)]
pub(crate) struct Problems {
    pub(crate) unmodeled: Vec<Unmodeled>,
    /// The uses whose declaration no translation holds.
    pub(crate) missing: Vec<Use>,
}

/// A generated module and the module of its group that holds the group's declarations: itself, or the one it imports.
pub(crate) struct Module {
    pub(crate) name: String,
    pub(crate) host: String,
    /// The generated modules it imports.
    pub(crate) imports: Vec<String>,
    pub(crate) text: String,
}

impl Problems {
    pub(crate) fn is_empty(&self) -> bool {
        self.unmodeled.is_empty() && self.missing.is_empty()
    }
}

impl<'program> Program<'program> {
    pub(crate) fn new(translations: &'program [Translation]) -> Self {
        let mut declarations = HashMap::default();
        for (index, translation) in translations.iter().enumerate() {
            for declaration in &translation.declarations {
                declarations.insert(declaration.key.as_str(), (index, declaration));
            }
        }

        let keys: Vec<&str> = declarations.keys().copied().collect();
        let positions: HashMap<&str, usize> = keys.iter().enumerate().map(|(position, key)| (*key, position)).collect();
        let successors: Vec<Vec<usize>> = keys
            .iter()
            .map(|key| {
                declarations[key].1.uses.iter().filter_map(|used| positions.get(used.key.as_str()).copied()).collect()
            })
            .collect();
        let mut recursive = HashMap::default();
        let mut terminating = HashSet::default();
        for part in strongly_connected_parts(&successors) {
            let cyclic = part.len() > 1 || part.iter().any(|node| successors[*node].contains(node));
            if !cyclic {
                continue;
            }
            let part: Vec<&str> = part.into_iter().map(|node| keys[node]).collect();
            if gets_smaller(&declarations, &part) {
                terminating.extend(part);
                continue;
            }
            let methods = part.iter().all(|key| declarations[key].1.unfolds);
            for key in part {
                recursive.insert(
                    key,
                    Unmodeled {
                        span: declarations[key].1.span,
                        what: if methods {
                            "a recursion that does not get smaller"
                        } else {
                            "a type that holds itself"
                        }
                        .to_owned(),
                        // A type is placed by its own name, as a member is by its class's and its own.
                        place: if methods { place_of(key) } else { key.rsplit('.').next().unwrap_or(key).to_owned() },
                        reason: if methods { issues::RECURSION } else { issues::SELF_HOLDING },
                    },
                );
            }
        }

        Self { translations, declarations, recursive, terminating }
    }

    /// Every declaration `key` uses, transitively, `key`'s own included.
    fn closure(&self, key: &str) -> (Vec<&'program str>, Vec<Use>) {
        let mut reached = Vec::new();
        let mut missing: Vec<Use> = Vec::new();
        let mut seen: HashSet<&str> = HashSet::default();
        let mut pending = vec![key];
        while let Some(next) = pending.pop() {
            let Some((&key, (_, declaration))) = self.declarations.get_key_value(next) else {
                continue;
            };
            if !seen.insert(key) {
                continue;
            }
            reached.push(key);
            for used in &declaration.uses {
                if self.declarations.contains_key(used.key.as_str()) {
                    pending.push(used.key.as_str());
                } else if !missing.iter().any(|known| known.key == used.key) {
                    missing.push(used.clone());
                }
            }
        }

        (reached, missing)
    }

    /// Why the declaration `key`, or one it uses, cannot be written to Lean.
    pub(crate) fn problems(&self, key: &str) -> Problems {
        let (reached, missing) = self.closure(key);
        let mut problems = Problems { unmodeled: Vec::new(), missing };
        for reached in reached {
            let declaration = self.declarations[reached].1;
            for construct in declaration.unmodeled.iter().chain(self.recursive.get(reached)) {
                if !problems.unmodeled.iter().any(|known| known.span == construct.span && known.what == construct.what)
                {
                    problems.unmodeled.push(construct.clone());
                }
            }
        }

        problems
    }

    /// The generated module of each translation that names one and declares something or is in `proved`, whose laws'
    /// theorems import it. A declaration that cannot be written to Lean is left out. Files whose declarations use each
    /// other form one group, whose declarations all live in the module that sorts first; each other module of the group
    /// imports it, so no two modules import each other, as Lean requires.
    pub(crate) fn modules(&self, proved: &[FileId]) -> Vec<Module> {
        let sound: HashSet<&str> =
            self.declarations.keys().copied().filter(|key| self.problems(key).is_empty()).collect();

        let named: Vec<usize> = (0..self.translations.len())
            .filter(|index| {
                let translation = &self.translations[*index];
                translation.class.is_some()
                    && (!translation.declarations.is_empty() || proved.contains(&translation.file))
            })
            .collect();
        let position: HashMap<usize, usize> =
            named.iter().enumerate().map(|(position, index)| (*index, position)).collect();
        let successors: Vec<Vec<usize>> = named
            .iter()
            .map(|index| {
                let mut successors: Vec<usize> = self.translations[*index]
                    .declarations
                    .iter()
                    .filter(|declaration| sound.contains(declaration.key.as_str()))
                    .flat_map(|declaration| &declaration.uses)
                    .filter_map(|used| self.declarations.get(used.key.as_str()))
                    .filter_map(|(used, _)| position.get(used).copied())
                    .filter(|used| *used != position[index])
                    .collect();
                successors.sort_unstable();
                successors.dedup();
                successors
            })
            .collect();

        let mut modules = Vec::new();
        let mut host_of: HashMap<usize, String> = HashMap::default();
        for part in strongly_connected_parts(&successors) {
            let mut members: Vec<(String, usize)> =
                part.iter().map(|position| (module_name(&self.translations[named[*position]]), *position)).collect();
            members.sort();
            let host = members[0].0.clone();
            for (_, position) in &members {
                host_of.insert(*position, host.clone());
            }

            let mut imports: Vec<String> = members
                .iter()
                .flat_map(|(_, position)| &successors[*position])
                .filter(|used| !part.contains(used))
                .map(|used| host_of[used].clone())
                .collect();
            imports.sort();
            imports.dedup();

            let mut text = String::from(HEADER);
            for import in &imports {
                let _ = writeln!(text, "import {import}");
            }
            text.push_str("open Sharp\n");
            text.push_str(OPTIONS);
            for group in self.ordered(members.iter().map(|(_, position)| named[*position]), &sound) {
                text.push('\n');
                text.push_str(&self.group_text(&group));
                text.push('\n');
            }
            for (name, _) in &members[1..] {
                modules.push(Module {
                    name: name.clone(),
                    host: host.clone(),
                    imports: vec![host.clone()],
                    text: format!("-- Generated by mago compile. Do not edit.\nimport {host}\n"),
                });
            }
            modules.push(Module { name: host.clone(), host, imports, text });
        }

        modules
    }

    /// The text of `group`, declarations that use each other or one alone, each method that recurses with the measure
    /// Lean sees it end by: methods that call each other are one Lean `mutual` block.
    fn group_text(&self, group: &[&str]) -> String {
        let texts: Vec<String> = group
            .iter()
            .map(|key| {
                let declaration = self.declarations[key].1;
                match &declaration.measure {
                    Some(measure) if self.terminating.contains(key) => {
                        format!("{}\n{}", declaration.text, measure.termination)
                    }
                    _ => declaration.text.clone(),
                }
            })
            .collect();

        match texts.as_slice() {
            [text] => text.clone(),
            _ => format!("mutual\n\n{}\n\nend", texts.join("\n\n")),
        }
    }

    /// The sound declarations of the translations at `indexes`, in groups that use each other, each group after every
    /// declaration it uses.
    fn ordered(&self, indexes: impl Iterator<Item = usize>, sound: &HashSet<&str>) -> Vec<Vec<&'program str>> {
        let mut keys: Vec<&str> = indexes
            .flat_map(|index| &self.translations[index].declarations)
            .map(|declaration| declaration.key.as_str())
            .filter(|key| sound.contains(key))
            .collect();
        keys.sort_unstable();
        let position: HashMap<&str, usize> = keys.iter().enumerate().map(|(position, key)| (*key, position)).collect();
        let successors: Vec<Vec<usize>> = keys
            .iter()
            .map(|key| {
                self.declarations[key]
                    .1
                    .uses
                    .iter()
                    .filter_map(|used| position.get(used.key.as_str()).copied())
                    .collect()
            })
            .collect();

        strongly_connected_parts(&successors)
            .into_iter()
            .map(|part| part.into_iter().map(|position| keys[position]).collect())
            .collect()
    }
}

/// Whether the methods `part`, of one class, each make one parameter smaller by one step on every call among them, and
/// pass that smaller value as the parameter the method they call makes smaller by the same step, so each of their
/// measures falls on every call and Lean sees the recursion end.
fn gets_smaller(declarations: &HashMap<&str, (usize, &Declaration)>, part: &[&str]) -> bool {
    let class = |key: &str| key.rsplit_once('.').map(|(class, _)| class.to_owned());
    part.iter().all(|key| {
        let Some(measure) = &declarations[key].1.measure else {
            return false;
        };
        class(key) == class(part[0])
            && declarations[key].1.uses.iter().filter(|used| part.contains(&used.key.as_str())).all(|used| {
                let callee = declarations[used.key.as_str()].1.measure.as_ref();
                used.smaller.is_some_and(|smaller| {
                    smaller.parameter == measure.parameter
                        && callee
                            .is_some_and(|callee| (smaller.argument, &smaller.step) == (callee.parameter, &callee.step))
                })
            })
    })
}

/// The generated module of `translation`: `Code.` and its class's Lean name.
pub(crate) fn module_name(translation: &Translation) -> String {
    format!("Code.{}", translation.class.as_ref().map_or("", |(class, _)| class.as_str()))
}

/// `Money.add` of `App.Shared.Money.add`.
pub(crate) fn place_of(key: &str) -> String {
    let mut parts = key.rsplitn(3, '.');
    match (parts.next(), parts.next()) {
        (Some(member), Some(class)) => format!("{class}.{member}"),
        (Some(name), None) => name.to_owned(),
        _ => key.to_owned(),
    }
}

#[derive(Serialize)]
struct Lakefile<'lakefile> {
    name: &'lakefile str,
    require: [Require<'lakefile>; 1],
}

#[derive(Serialize)]
struct Require<'lakefile> {
    name: &'lakefile str,
    path: &'lakefile Path,
}

/// Why Lean did not elaborate a generated module.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Refusal {
    /// Lean ran past the processor-time limit, or waited until Mago's deadline.
    Stopped(Stop),
    /// Lean rejected the module, at the line of its first error, or at line 0 when the error has no line: an import the
    /// request holds no module for.
    Rejected(u32),
}

/// What `lake` answered when asked its version.
pub(crate) enum Toolchain {
    Ready,
    /// No `lake` is on the `PATH`, and the Mago build pins no elan for its target.
    Unsupported,
    /// Mago could not install Lean where no `lake` is on the `PATH`, or `lake` could not install the pinned Lean
    /// version, with what failed.
    Failed(String),
}

/// The package in `.sharp/.lean/` under a workspace root, and the `lake` that runs the runner in it.
pub(crate) struct Package {
    pub(crate) directory: PathBuf,
    pub(crate) lake: Lake,
}

impl Package {
    /// The package of the workspace at `root`, in `.sharp/.lean/` apart from the `.sharpc` mirror of the sources, with
    /// the `lake` on the `PATH`. The folder is joined one name at a time, since `cmd` reads a `/` in a Windows path as
    /// a switch.
    pub(crate) fn new(root: &Path) -> Self {
        Self { directory: plain(root).join(COMPILED_FOLDER).join(PACKAGE_FOLDER), lake: Lake::on_path() }
    }

    /// Writes the package's Lean version, so elan installs it on first use, and asks `lake` for its version there, under
    /// `library::first_call`'s lock. With no `lake` on the `PATH`, the package uses the `lake` of the elan Mago installs in
    /// its cache folder.
    pub(crate) fn toolchain(&mut self) -> io::Result<Toolchain> {
        fs::create_dir_all(&self.directory)
            .map_err(|error| DatabaseError::io(IOAction::CreateFolder, &self.directory, error))?;
        write_if_changed(&self.directory.join("lean-toolchain"), library::TOOLCHAIN.as_bytes())?;

        let output = match library::first_call(self.lake.command().arg("--version").current_dir(&self.directory)) {
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                self.lake = match library::install() {
                    Ok(Some(lake)) => lake,
                    Ok(None) => return Ok(Toolchain::Unsupported),
                    Err(error) => return Ok(Toolchain::Failed(error.to_string())),
                };
                self.lake.command().arg("--version").current_dir(&self.directory).output()?
            }
            output => output?,
        };

        Ok(if output.status.success() {
            Toolchain::Ready
        } else {
            Toolchain::Failed(
                format!("{}{}", String::from_utf8_lossy(&output.stderr), String::from_utf8_lossy(&output.stdout))
                    .trim()
                    .to_owned(),
            )
        })
    }

    /// Writes `lakefile.toml`, which requires the runtime library by path, so `lake env` gives the runner its search
    /// path. A changed `lakefile.toml` drops Lake's manifest, so Lake resolves the library again. The runner gets the
    /// generated modules in its request, so the package holds none: the sources and the build of them an older Mago
    /// left are deleted.
    pub(crate) fn write(&self, library: &Path) -> io::Result<()> {
        let lakefile = toml::to_string(&Lakefile { name: "laws", require: [Require { name: "sharp", path: library }] })
            .map_err(io::Error::other)?;
        if write_if_changed(&self.directory.join("lakefile.toml"), lakefile.as_bytes())? {
            let manifest = self.directory.join("lake-manifest.json");
            match fs::remove_file(&manifest) {
                Err(error) if error.kind() != io::ErrorKind::NotFound => {
                    return Err(DatabaseError::io(IOAction::DeleteFile, &manifest, error).into());
                }
                _ => {}
            }
        }

        for stale in [self.directory.join("Code"), self.directory.join(".lake").join("build")] {
            match fs::remove_dir_all(&stale) {
                Err(error) if error.kind() != io::ErrorKind::NotFound => {
                    return Err(DatabaseError::io(IOAction::DeleteFolder, &stale, error).into());
                }
                _ => {}
            }
        }

        Ok(())
    }
}

/// Writes `bytes` to `path` by rename unless the file already holds them, so a reader never sees a file half written,
/// and an unchanged file keeps its modification time. Returns whether it wrote.
fn write_if_changed(path: &Path, bytes: &[u8]) -> Result<bool, DatabaseError> {
    if fs::read(path).is_ok_and(|current| current == bytes) {
        return Ok(false);
    }

    let folder = path.parent().unwrap_or(path);
    fs::create_dir_all(folder).map_err(|error| DatabaseError::io(IOAction::CreateFolder, folder, error))?;
    let failed = |error: io::Error| DatabaseError::io(IOAction::WriteFile, path, error);
    let file = tempfile::NamedTempFile::new_in(folder).map_err(failed)?;
    fs::write(file.path(), bytes).map_err(failed)?;
    let (file, written) = file.keep().map_err(|error| failed(error.error))?;
    drop(file);
    fs::rename(&written, path)
        .inspect_err(|_| {
            let _ = fs::remove_file(&written);
        })
        .map_err(failed)?;

    Ok(true)
}

/// `path` without the `\\?\` prefix `canonicalize` gives a Windows path, which neither `cmd` nor Lake reads.
fn plain(path: &Path) -> PathBuf {
    match path.to_str().and_then(|path| path.strip_prefix(r"\\?\")) {
        Some(rest) if !rest.starts_with(r"UNC\") => PathBuf::from(rest),
        _ => path.to_path_buf(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_verbatim_windows_path_loses_its_prefix_and_any_other_path_is_kept() {
        assert_eq!(plain(Path::new(r"\\?\C:\work\app")), PathBuf::from(r"C:\work\app"));
        assert_eq!(plain(Path::new(r"\\?\UNC\server\share")), PathBuf::from(r"\\?\UNC\server\share"));
        assert_eq!(plain(Path::new("/work/app")), PathBuf::from("/work/app"));
    }

    #[test]
    fn a_member_is_placed_by_its_class_and_name() {
        assert_eq!(place_of("App.Shared.Money.add"), "Money.add");
    }
}
